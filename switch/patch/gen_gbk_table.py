#!/usr/bin/env python3
"""Generate gbk_table.h for OpenMW's toutf8 component.

The table maps GBK double-byte sequences to Unicode code points, using the
host Python's 'gbk' codec, so the build needs no iconv and no locale data.

Index layout:
    lead  : 0x81..0xFE          -> 126 values
    trail : 0x40..0xFE          -> 191 values
    index = (lead - 0x81) * 191 + (trail - 0x40)

Unmapped entries are 0.
"""
import sys

LEAD_MIN, LEAD_MAX = 0x81, 0xFE
TRAIL_MIN, TRAIL_MAX = 0x40, 0xFE
N_LEAD = LEAD_MAX - LEAD_MIN + 1
N_TRAIL = TRAIL_MAX - TRAIL_MIN + 1

table = [0] * (N_LEAD * N_TRAIL)

valid = 0
for lead in range(LEAD_MIN, LEAD_MAX + 1):
    for trail in range(TRAIL_MIN, TRAIL_MAX + 1):
        try:
            ch = bytes([lead, trail]).decode("gbk")
        except UnicodeDecodeError:
            continue
        if len(ch) != 1:
            continue
        cp = ord(ch)
        if cp > 0xFFFF:
            continue
        idx = (lead - LEAD_MIN) * N_TRAIL + (trail - TRAIL_MIN)
        table[idx] = cp
        valid += 1

out = []
out.append("// Generated by gen_gbk_table.py - do not edit.")
out.append("// GBK lead 0x81-0xFE, trail 0x40-0xFE, index = (lead-0x81)*%d + (trail-0x40)" % N_TRAIL)
out.append("#pragma once")
out.append("#define GBK_LEAD_MIN 0x%02X" % LEAD_MIN)
out.append("#define GBK_LEAD_MAX 0x%02X" % LEAD_MAX)
out.append("#define GBK_TRAIL_MIN 0x%02X" % TRAIL_MIN)
out.append("#define GBK_TRAIL_MAX 0x%02X" % TRAIL_MAX)
out.append("#define GBK_TRAIL_COUNT %d" % N_TRAIL)
out.append("#define GBK_TABLE_SIZE %d" % len(table))
out.append("static const unsigned short gbk_table[GBK_TABLE_SIZE] = {")
for i in range(0, len(table), 12):
    chunk = ", ".join("0x%04X" % v for v in table[i:i + 12])
    out.append("    " + chunk + ",")
out.append("};")
out.append("")

with open(sys.argv[1] if len(sys.argv) > 1 else "gbk_table.h", "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))

print("wrote gbk_table.h: %d entries, %d valid" % (len(table), valid))
